/** Verify cumulative immutable migrations, or print ONLY unpublished levels. */
import { readFileSync, readdirSync } from 'node:fs';
import assert from 'node:assert/strict';
import { LEVELS, CATALOG_VERSION, solve } from '../src/puzzle.ts';

const directory = new URL('../supabase/migrations/', import.meta.url);
const literal = value => `'${String(value).replaceAll("'", "''")}'`;
const published = new Map();
for (const filename of readdirSync(directory).filter(name => name.endsWith('.sql')).sort()) {
  const sql = readFileSync(new URL(filename, directory), 'utf8');
  for (const block of sql.matchAll(/-- CATALOG_SEED_BEGIN[^\n]*\n([\s\S]*?)-- CATALOG_SEED_END/g)) {
    for (const row of block[1].matchAll(/\('((?:[^']|'')*)','((?:[^']|'')*)',(true|false),'((?:[^']|'')*)'::jsonb\)/g)) {
      const [, key, version, ranked, pieces] = row;
      assert.ok(!published.has(key), `Duplicate published identity ${key} in ${filename}`);
      published.set(key, { version, ranked: ranked === 'true', pieces: JSON.parse(pieces.replaceAll("''", "'")) });
    }
  }
}
const geometry = level => level.pieces.map(({ id, position, direction }) => ({ id, position, direction }));
const missing = LEVELS.filter(level => !published.has(level.key));
for (const level of LEVELS) {
  const existing = published.get(level.key);
  if (!existing) continue;
  assert.deepEqual(existing.pieces, geometry(level), `Published puzzle changed: ${level.key}. Assign a new key instead.`);
  assert.equal(existing.ranked, level.id > 0, `Published ranking status changed: ${level.key}`);
}
for (const key of published.keys()) assert.ok(LEVELS.some(level => level.key === key), `Published identity removed: ${key}`);
const solutions = Object.fromEntries(LEVELS.filter(level => level.id > 0).map(level => {
  const order = solve(level.pieces);
  assert.ok(order, `Unsolvable level ${level.key}`);
  return [level.key, order];
}));
const fixture = `-- SOLUTION_FIXTURES_BEGIN\nselect pg_catalog.set_config('test.solutions',${literal(JSON.stringify(solutions))},true);\n-- SOLUTION_FIXTURES_END`;
const mode = process.argv[2] ?? '--check';
if (mode === '--print') {
  assert.ok(missing.length, 'No unpublished levels.');
  const rows = missing.map(level => `(${literal(level.key)},${literal(CATALOG_VERSION)},${level.id > 0},${literal(JSON.stringify(geometry(level)))}::jsonb)`);
  console.log(`-- CATALOG_SEED_BEGIN (generated by scripts/export-catalog.mjs)\ninsert into svela_private.puzzle_catalog(level_key,catalog_version,ranked,pieces) values\n${rows.join(',\n')};\n-- CATALOG_SEED_END`);
} else if (mode === '--fixtures') {
  console.log(fixture);
} else if (mode === '--check') {
  assert.equal(missing.length, 0, `Unpublished levels: ${missing.map(level => level.key).join(', ')}`);
  assert.ok(readFileSync(new URL('../supabase/tests/campaign.sql', import.meta.url), 'utf8').includes(fixture), 'Solution fixtures differ. Regenerate with --fixtures.');
  console.log(`Verified ${published.size} immutable catalog identities and ${Object.keys(solutions).length} complete solutions across migrations.`);
} else {
  throw new Error('Usage: node scripts/export-catalog.mjs [--check|--print|--fixtures]');
}
