/** Check published fixtures, or print a seed for review in a NEW migration. */
import { readFileSync } from 'node:fs';
import assert from 'node:assert/strict';
import { LEVELS, CATALOG_VERSION, solve } from '../src/puzzle.ts';
const path = new URL('../supabase/migrations/20261101162235_fantasy_campaign_rankings.sql', import.meta.url);
const literal = (value) => `'${String(value).replaceAll("'", "''")}'`;
const rows = LEVELS.map((level) => `(${literal(level.key)},${literal(CATALOG_VERSION)},${level.id > 0},${literal(JSON.stringify(level.pieces.map(({ id, position, direction }) => ({ id, position, direction }))))}::jsonb)`);
const seed = `-- CATALOG_SEED_BEGIN (generated by scripts/export-catalog.mjs)\ninsert into svela_private.puzzle_catalog(level_key,catalog_version,ranked,pieces) values\n${rows.join(',\n')};\n-- CATALOG_SEED_END`;
const testPath = new URL('../supabase/tests/campaign.sql', import.meta.url);
const solutions = Object.fromEntries(LEVELS.filter((level) => level.id > 0).map((level) => [level.key, solve(level.pieces)]));
const fixture = `-- SOLUTION_FIXTURES_BEGIN\nselect pg_catalog.set_config('test.solutions',${literal(JSON.stringify(solutions))},true);\n-- SOLUTION_FIXTURES_END`;
const mode = process.argv[2] ?? '--check';
if (mode === '--print') {
  // Existing versioned keys are immutable: new migrations add new keys only.
  console.log(seed.replace(/;\n-- CATALOG_SEED_END$/, '\non conflict (level_key) do nothing;\n-- CATALOG_SEED_END'));
} else if (mode === '--check') {
  assert.ok(readFileSync(path, 'utf8').includes(seed), 'Published catalog differs: use a new versioned level key and migration.');
  assert.ok(readFileSync(testPath, 'utf8').includes(fixture), 'Solution fixtures differ from the shipped puzzles.');
  console.log(`Verified ${LEVELS.length} catalog identities and ${Object.keys(solutions).length} complete solutions.`);
} else {
  throw new Error('Usage: node scripts/export-catalog.mjs [--check|--print]');
}
